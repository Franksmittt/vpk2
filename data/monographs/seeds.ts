import type { QuarrySpecies } from "@/data/species";
import type { MonographImageSeeds } from "./types";

export function monoSeeds(
  s: QuarrySpecies,
  useIntroCard: boolean,
  keys: Partial<MonographImageSeeds> = {},
): MonographImageSeeds {
  const p = s.imageSeed;
  return {
    hero: keys.hero ?? `${p}monohero`,
    heroLocalBase: keys.heroLocalBase,
    heroLocalExt: keys.heroLocalExt,
    intro: keys.intro ?? `${p}monintro`,
    introLocalBase: keys.introLocalBase,
    introLocalExt: keys.introLocalExt,
    useIntroCardImage: keys.useIntroCardImage ?? useIntroCard,
    panorama: keys.panorama ?? `${p}monopan`,
    formPrimary: keys.formPrimary ?? `${p}monoforma`,
    formPrimaryLocalBase: keys.formPrimaryLocalBase,
    formPrimaryLocalExt: keys.formPrimaryLocalExt,
    formSecondary: keys.formSecondary ?? `${p}monoformb`,
    formSecondaryLocalBase: keys.formSecondaryLocalBase,
    formSecondaryLocalExt: keys.formSecondaryLocalExt,
    hornsLocalBase: keys.hornsLocalBase,
    hornsLocalExt: keys.hornsLocalExt,
    ecology: keys.ecology ?? `${p}monoeco`,
    ecologyLocalBase: keys.ecologyLocalBase,
    ecologyLocalExt: keys.ecologyLocalExt,
    feedWide: keys.feedWide ?? `${p}monofeed`,
    feedWideLocalBase: keys.feedWideLocalBase,
    feedWideLocalExt: keys.feedWideLocalExt,
    rutLeft: keys.rutLeft ?? `${p}monorut`,
    rutLeftLocalBase: keys.rutLeftLocalBase,
    rutLeftLocalExt: keys.rutLeftLocalExt,
    predation: keys.predation ?? `${p}monopred`,
    predationLocalBase: keys.predationLocalBase,
    predationLocalExt: keys.predationLocalExt,
    hunt: keys.hunt ?? `${p}monohunt`,
    huntLocalBase: keys.huntLocalBase,
    huntLocalExt: keys.huntLocalExt,
    trophy: keys.trophy ?? `${p}monotrophy`,
    trophyLocalBase: keys.trophyLocalBase,
    trophyLocalExt: keys.trophyLocalExt,
    rifle: keys.rifle ?? `${p}monorifle`,
    rifleLocalBase: keys.rifleLocalBase,
    rifleLocalExt: keys.rifleLocalExt,
    meat: keys.meat ?? `${p}monomeat`,
    meatLocalBase: keys.meatLocalBase,
    meatLocalExt: keys.meatLocalExt,
    panoramaLocalBase: keys.panoramaLocalBase,
    panoramaLocalExt: keys.panoramaLocalExt,
  };
}
